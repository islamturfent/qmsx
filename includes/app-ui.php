/**
 * Avatar yoksa gosterilecek bas harfler (en fazla iki harf).
 */
function appInitials(string $name): string
{
    $initials = '';

    foreach (preg_split('/\s+/', trim($name)) ?: [] as $part) {
        if ($part === '') {
            continue;
        }
        $initials .= function_exists('mb_substr')
            ? mb_strtoupper(mb_substr($part, 0, 1, 'UTF-8'), 'UTF-8')
            : strtoupper(substr($part, 0, 1));
        if (function_exists('mb_strlen') ? mb_strlen($initials, 'UTF-8') >= 2 : strlen($initials) >= 2) {
            break;
        }
    }

    return $initials;
}
